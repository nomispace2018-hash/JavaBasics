public class Decimals {
	public static void main(String[] args) {
		
		//0
		double x = 12.3456789;
		int n = 0;
		int result = (int)Math.round(x * Math.pow(10, n) / Math.pow(10.0, n));
		System.out.println("Rounded to " + n + " decimals: " + result);
		
		
		//2
		n = 2;
		
		
		
		//4
		n = 4;
		
		
		//6
		n = 6;
		
		
	}
}