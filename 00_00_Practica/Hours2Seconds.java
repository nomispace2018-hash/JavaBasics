public class Hours2Seconds {
	public static void main(String[] args) {
		
		// Calcular 12h
		int hours = 12;
		int seconds = 60*60;
		System.out.println(hours + " hours are " + (seconds * hours) + " seconds");
		
		// Calcular 15h
		hours = 15;
		seconds = 60*60;
		System.out.println(hours + " hours are " + (seconds * hours) + " seconds");
		
		// Calcular 23h
		hours =  23;
		seconds = 60 * 60;
		System.out.println(hours + " hours are " + (seconds * hours) + " seconds");
		
		
	}
}